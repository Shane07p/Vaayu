const I18n = createContext<{ language: Language; setLanguage: (language: Language) => void; t: Copy }>({ language: "en", setLanguage: () => {}, t: copy.en });
export function CitizenI18nProvider({ children }: { children: React.ReactNode }) { const [language, setLanguage] = useState<Language>("en"); useEffect(() => { const timer = window.setTimeout(() => { const saved = localStorage.getItem("vaayu-language") as Language | null; if (saved && copy[saved]) setLanguage(saved); }, 0); return () => window.clearTimeout(timer); }, []); const choose = (next: Language) => { setLanguage(next); localStorage.setItem("vaayu-language", next); }; return <I18n.Provider value={{ language, setLanguage: choose, t: copy[language] }}>{children}</I18n.Provider>; }
export const useCitizenI18n = () => useContext(I18n);
